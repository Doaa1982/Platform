            // matches nothing.
            entity.Property(e => e.Id).ValueGeneratedNever();

            entity.Property(e => e.Name)
                  .IsRequired()
                  .HasMaxLength(256);

            entity.Property(e => e.Slug)
                  .IsRequired()

            entity.HasIndex(e => new { e.IdentityId, e.WorkspaceId }).IsUnique();

            // Lookup path for "which Workspaces does this Identity belong to?"
            entity.HasIndex(e => e.IdentityId);

            entity.Property(e => e.Status)
